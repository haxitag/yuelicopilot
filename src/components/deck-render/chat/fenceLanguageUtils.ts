export function syntaxHighlighterLanguageFromFenceInfo(info: string): string {
  const t = info.trim();
  if (!t) return 'text';
  if (/[^\u0000-\u007f]/.test(t)) return 'text';
  if (!/^[a-zA-Z0-9_.+-]+$/.test(t)) return 'text';
  return t.toLowerCase();
}

