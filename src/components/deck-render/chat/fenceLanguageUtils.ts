/** `str` = 源码中紧邻 ``` 之后（不含三个反引号）的子串开头 */
export function isLikelyFenceOpenerAfterBackticks(str: string): boolean {
  const m = str.match(/^\s*([A-Za-z0-9_.+#-]+)/);
  if (!m) return false;
  const w = m[1].toLowerCase();
  return FENCE_INFO_ALLOWLIST.has(w);
}
